"""Writes tests/golden/features-psl-f1.json: expected feature outputs that the
TypeScript implementation must reproduce (tests/features.test.ts) and the
Python implementation must keep reproducing (training/tests/test_features.py).

Inputs:
  - REAL frames captured from the browser pipeline (tests/golden/frames-fixture-*.json)
  - REAL frames from one PSL dictionary recording (tests/golden/frames-psl-dictionary-help.json)
  - SYNTHETIC edge cases, built below and named "synthetic-..." (missing pose,
    missing hands, degenerate hand). Synthetic data appears only in tests.

Run from the repo root: training/.venv/bin/python -m training.make_golden
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from training.psl.features import (FEATURE_VERSION, WINDOW_MS, WINDOW_T, RawFrame, mirror_frame,
                                   recording_features, resample_window)

ROOT = Path(__file__).resolve().parents[1]
GOLDEN = ROOT / "tests" / "golden"


def load(name: str):
    d = json.loads((GOLDEN / name).read_text())
    return [RawFrame.from_json(f) for f in d["frames"]], d["frames"]


def synthetic_cases(base_json: list) -> dict:
    """Edge cases derived by deleting parts of real frames (labelled synthetic)."""
    cases = {}
    no_pose_start = [dict(f) for f in base_json[:20]]
    for f in no_pose_start[:6]:
        f["pose"] = None  # body frame must carry from the first later pose
    cases["synthetic-no-pose-at-start"] = no_pose_start
    no_pose = [dict(f, pose=None) for f in base_json[:10]]
    cases["synthetic-no-pose-at-all"] = no_pose
    no_hands = [dict(f, left=None, right=None) for f in base_json[:10]]
    cases["synthetic-no-hands"] = no_hands
    degenerate = [dict(f) for f in base_json[:5]]
    for f in degenerate:
        if f["right"] is not None:
            f["right"] = [f["right"][0]] * 21  # all points at the wrist: H < 1e-6
    cases["synthetic-degenerate-hand"] = degenerate
    return cases


def window_ends(times):
    t0, t1 = times[0], times[-1]
    mid = times[len(times) // 2]
    return [t1, mid, (mid + times[len(times) // 2 + 1]) / 2, t0 - 500.0, t0 + 300.0]


def make_case(name: str, frames_json: list, mirror: bool) -> dict:
    frames = [RawFrame.from_json(f) for f in frames_json]
    if mirror:
        frames = [mirror_frame(f) for f in frames]
    feats = recording_features(frames)
    times = [f.t for f in frames]
    windows = []
    for t_end in window_ends(times):
        for T, W in ((WINDOW_T, WINDOW_MS), (8, 400.0)):
            windows.append({"tEnd": t_end, "T": T, "windowMs": W,
                            "out": np.round(resample_window(times, feats, t_end, T, W).astype(float), 7).tolist()})
    return {"name": name + (" (mirrored)" if mirror else ""), "mirror": mirror, "frames": frames_json,
            "frameFeatures": np.round(feats.astype(float), 7).tolist(), "windows": windows}


def main():
    sources = {}
    for f in sorted(GOLDEN.glob("frames-*.json")):
        d = json.loads(f.read_text())
        sources[f.stem.replace("frames-", "real-")] = d["frames"]
    first = next(iter(sources.values()))
    sources.update(synthetic_cases(first))
    cases = []
    for name, fj in sources.items():
        cases.append(make_case(name, fj, mirror=False))
        if name.startswith("real-"):
            cases.append(make_case(name, fj, mirror=True))
    out = {"feature_version": FEATURE_VERSION, "tolerance": 1e-5,
           "note": "Generated by training/make_golden.py. Cases named real-* are real landmarks; synthetic-* are test-only edge cases.",
           "cases": cases}
    path = GOLDEN / f"features-{FEATURE_VERSION}.json"
    # 7 decimals is far below the 1e-5 tolerance and keeps the file small.
    path.write_text(json.dumps(out, default=float).replace("NaN", "null"))
    print(f"wrote {path} ({len(cases)} cases, {path.stat().st_size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
