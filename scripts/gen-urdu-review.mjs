// Generates docs/URDU_REVIEW.md: every Urdu string in the app, for a native
// speaker to check. Run: node scripts/gen-urdu-review.mjs
// Sources: src/i18n/strings.json (UI). signs.json and phrases.json are added in milestone 4.
import { readFile, writeFile, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const rows = [];

const ui = JSON.parse(await readFile(join(root, 'src/i18n/strings.json'), 'utf8'));
for (const [key, v] of Object.entries(ui)) {
  if (key.startsWith('_')) continue;
  rows.push({ source: 'UI', key, en: v.en, ur: v.ur, reviewed: v.reviewed });
}
for (const [file, label] of [['src/data/signs.json', 'Sign'], ['src/data/phrases.json', 'Phrase']]) {
  const exists = await stat(join(root, file)).then(() => true, () => false);
  if (!exists) continue;
  const data = JSON.parse(await readFile(join(root, file), 'utf8'));
  for (const item of data.items ?? data) {
    if (typeof item.ur === 'string') rows.push({ source: label, key: item.id, en: item.en, ur: item.ur, reviewed: item.reviewed });
    else if (item.ur && typeof item.ur === 'object') {
      for (const [form, ur] of Object.entries(item.ur)) {
        rows.push({ source: `${label} (${form})`, key: item.id, en: item.en?.[form] ?? item.en, ur, reviewed: item.reviewed });
      }
    }
  }
}

const pending = rows.filter((r) => !r.reviewed).length;
const out = [
  '# Urdu review',
  '',
  'Generated by `node scripts/gen-urdu-review.mjs`. Do not edit by hand: change the',
  'source JSON, set `reviewed: true` once a native Urdu speaker has approved a string,',
  'and regenerate.',
  '',
  `**${pending} of ${rows.length} strings are not reviewed yet.**`,
  '',
  'For each row: is the Urdu natural, correct and the right register for a',
  'conversation between a Deaf signer and a hearing person? Write corrections in',
  'the last column (or send them back in any form).',
  '',
  '| Source | Key | English | Urdu | Reviewed | Correction |',
  '|---|---|---|---|---|---|',
  ...rows.map((r) => `| ${r.source} | \`${r.key}\` | ${esc(r.en)} | <span dir="rtl" lang="ur">${esc(r.ur)}</span> | ${r.reviewed ? 'yes' : '**no**'} | |`),
  '',
];
await writeFile(join(root, 'docs/URDU_REVIEW.md'), out.join('\n'));
console.log(`wrote docs/URDU_REVIEW.md (${rows.length} strings, ${pending} unreviewed)`);
